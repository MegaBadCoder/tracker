import { describe, expect, it } from 'vitest'
import { pluralRu } from '@/lib/plural'

describe('pluralRu', () => {
  it('выбирает форму для 1', () => {
    expect(pluralRu(1, ['история', 'истории', 'историй'])).toBe('история')
  })

  it('выбирает форму для 2', () => {
    expect(pluralRu(2, ['история', 'истории', 'историй'])).toBe('истории')
  })

  it('выбирает форму для 5', () => {
    expect(pluralRu(5, ['история', 'истории', 'историй'])).toBe('историй')
  })

  it('выбирает форму many для 11 (исключение из общего правила)', () => {
    expect(pluralRu(11, ['история', 'истории', 'историй'])).toBe('историй')
  })

  it('выбирает форму one для 21 (последняя цифра 1, но не 11)', () => {
    expect(pluralRu(21, ['история', 'истории', 'историй'])).toBe('история')
  })

  it('выбирает форму many для 0', () => {
    expect(pluralRu(0, ['история', 'истории', 'историй'])).toBe('историй')
  })
})
