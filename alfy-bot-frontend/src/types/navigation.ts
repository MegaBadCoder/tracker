import type { Component } from 'vue'

export interface NavLink {
  to: string
  label: string
  icon: Component
  /** Опциональный бейдж справа от пункта, напр. "скоро" для разделов в разработке. */
  badge?: string
  /**
   * Счётчик справа от пункта. Тунк, а не число: массивы ссылок собираются на
   * уровне модуля, до подъёма Pinia, поэтому стор можно трогать только внутри
   * вызова — уже в setup-контексте. `now` приходит аргументом, чтобы счётчик
   * пересчитывался вместе с часами и переживал полночь.
   */
  count?: (now: Date) => number
}
